import {
  CreateBucketCommand,
  DeleteObjectCommand,
  GetObjectCommand,
  HeadBucketCommand,
  PutObjectCommand,
  S3Client,
  S3ServiceException,
} from "@aws-sdk/client-s3";
import {
  Injectable,
  Logger,
  type OnApplicationBootstrap,
  type OnModuleDestroy,
} from "@nestjs/common";
import { describeError } from "../common/errors.js";
import { AppConfig } from "../config/app-config.js";

/**
 * S3-compatible object storage behind one service (the StorageProvider abstraction, ARCHITECTURE §20).
 * Locally this is RustFS; in the cloud it is S3 or a compatible service. Buckets are private.
 */
@Injectable()
export class StorageService implements OnApplicationBootstrap, OnModuleDestroy {
  private readonly logger = new Logger(StorageService.name);
  private readonly s3: S3Client;
  readonly bucket: string;

  constructor(private readonly config: AppConfig) {
    this.bucket = config.get("S3_BUCKET");
    this.s3 = new S3Client({
      endpoint: config.get("S3_ENDPOINT"),
      region: config.get("S3_REGION"),
      forcePathStyle: config.get("S3_FORCE_PATH_STYLE"),
      maxAttempts: 2,
      credentials: {
        accessKeyId: config.get("S3_ACCESS_KEY_ID"),
        secretAccessKey: config.get("S3_SECRET_ACCESS_KEY"),
      },
    });
  }

  async onApplicationBootstrap(): Promise<void> {
    if (!this.config.get("S3_AUTO_CREATE_BUCKET")) return;
    try {
      await this.ensureBucket();
    } catch (error) {
      this.logger.warn(`Could not ensure bucket "${this.bucket}": ${describeError(error)}`);
    }
  }

  async ping(signal?: AbortSignal): Promise<void> {
    await this.s3.send(new HeadBucketCommand({ Bucket: this.bucket }), { abortSignal: signal });
  }

  /**
   * Stores a private object. Keys are always generated by the API (tenant/project-scoped), never
   * taken from user input. The SHA-256 is sent so the store verifies the bytes it received.
   */
  async put(key: string, body: Buffer, contentType: string, sha256?: string): Promise<void> {
    await this.s3.send(
      new PutObjectCommand({
        Bucket: this.bucket,
        Key: key,
        Body: body,
        ContentType: contentType,
        ContentLength: body.length,
        ...(sha256 ? { ChecksumSHA256: Buffer.from(sha256, "hex").toString("base64") } : {}),
      }),
    );
  }

  /** Reads a private object into memory, refusing anything larger than `maxBytes`. */
  async get(key: string, maxBytes: number): Promise<Buffer> {
    const response = await this.s3.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
    if ((response.ContentLength ?? 0) > maxBytes) throw new Error("Stored object is too large");
    const bytes = await response.Body?.transformToByteArray();
    if (!bytes) throw new Error("Stored object has no content");
    if (bytes.length > maxBytes) throw new Error("Stored object is too large");
    return Buffer.from(bytes);
  }

  async delete(key: string): Promise<void> {
    await this.s3.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }

  private async ensureBucket(): Promise<void> {
    try {
      await this.ping();
    } catch (error) {
      const notFound =
        error instanceof S3ServiceException && error.$metadata.httpStatusCode === 404;
      if (!notFound) throw error;
      await this.s3.send(new CreateBucketCommand({ Bucket: this.bucket }));
      this.logger.log(`Created development bucket "${this.bucket}"`);
    }
  }

  onModuleDestroy(): void {
    this.s3.destroy();
  }
}
