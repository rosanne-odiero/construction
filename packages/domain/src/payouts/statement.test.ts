import { describe, expect, it } from "vitest";
import {
  excelSerialDate,
  maskPartyInfo,
  parseStatementAmount,
  parseStatementCsv,
  parseStatementRows,
  parseStatementTime,
  splitCsv,
} from "../index.js";

/** A synthetic organisation-portal export: preamble rows, quoted cells, an unknown column. */
const EXPORT = [
  '"Account Name:","MJENZI BORA LTD"',
  '"Short Code:","600123"',
  '"Time Period:","From 16-11-2026 00:00:00 To 16-11-2026 23:59:59"',
  "",
  '"Receipt No.","Completion Time","Initiation Time","Details","Transaction Status","Paid In","Withdrawn","Balance","Balance Confirmed","Reason Type","Other Party Info","Linked Transaction ID","A/C No."',
  '"TKG7AB12CD","16-11-2026 09:15:02","16-11-2026 09:15:01","Salary Payment to 254712345678 - JOHN DOE","Completed","","-4,000.00","96,000.00","true","Salary Payment","254712345678 - JOHN DOE","",""',
  '"TKG7AB12CE","16-11-2026 09:15:02","16-11-2026 09:15:01","Salary Payment Charge","Completed","","-9.00","95,991.00","true","Business Payment Charge","","TKG7AB12CD",""',
  '"TKG7AB12CF","16-11-2026 10:00:00","","Funds received from 600000 - MJENZI BORA LTD","Completed","100,000.00","","195,991.00","true","Organization Transfer","600000 - MJENZI BORA LTD","",""',
  '"TKG7AB12CG","16-11-2026 11:00:00","","Transfer from Utility Account to Working Account","Completed","","-1,000.00","194,991.00","true","Funds Movement","","",""',
  '"TKG7AB12CH","16-11-2026 12:00:00","","Salary Payment to 254700000001 - PETER KAMAU","Failed","","-500.00","","","","","",""',
  '"TKG7AB12CJ","16-11-2026 13:30:45","","Payment to ""ABC, Builders"" Ltd","Completed","","1 250.50","193,740.50","true","Business Payment","600999 - ABC BUILDERS","",""',
  '"TKG7AB12CJ","16-11-2026 13:30:45","","Business Payment Charge","Completed","","-13.00","193,727.50","true","Business Payment Charge","","",""',
  "",
  '"Disclaimer: generated by the M-PESA organisation portal"',
].join("\r\n");

describe("CSV splitting", () => {
  it("handles quotes, doubled quotes, delimiters and line breaks inside quotes", () => {
    expect(splitCsv('\ufeffa,"b,c","d ""e""",\r\n"x\ny",z')).toEqual([
      ["a", "b,c", 'd "e"', ""],
      ["x\ny", "z"],
    ]);
    expect(splitCsv("a;b\tc", ";")).toEqual([["a", "b\tc"]]);
  });
});

describe("M-Pesa statement parser (§11)", () => {
  it("finds the header below the preamble and reads every transaction line", () => {
    const parsed = parseStatementCsv(EXPORT);
    if (!parsed.ok) throw new Error(parsed.error);
    expect(parsed.headerRow).toBe(5);
    expect(parsed.columns).toEqual([
      "receipt",
      "completionTime",
      "initiationTime",
      "details",
      "transactionStatus",
      "paidIn",
      "withdrawn",
      "balance",
      "reasonType",
      "otherPartyInfo",
      "linkedTransactionId",
      "accountNumber",
    ]);
    expect(parsed.issues).toEqual([]);
    expect(parsed.period).toEqual({ from: "2026-11-16", to: "2026-11-16" });
    expect(parsed.lines.map((line) => [line.receipt, line.lineClass, line.chargeFor])).toEqual([
      ["TKG7AB12CD", "payout", null],
      ["TKG7AB12CE", "charge", "TKG7AB12CD"],
      ["TKG7AB12CF", "deposit", null],
      ["TKG7AB12CG", "other", null],
      ["TKG7AB12CH", "other", null],
      ["TKG7AB12CJ", "payout", null],
      ["TKG7AB12CJ", "charge", "TKG7AB12CJ"],
    ]);
    expect(parsed.lines[0]).toEqual({
      row: 6,
      receipt: "TKG7AB12CD",
      completedAt: "2026-11-16T09:15:02+03:00",
      completedOn: "2026-11-16",
      initiatedAt: "2026-11-16T09:15:01+03:00",
      details: "Salary Payment to 254712345678 - JOHN DOE",
      transactionStatus: "Completed",
      paidInMinor: 0,
      withdrawnMinor: 400_000,
      balanceMinor: 9_600_000,
      reasonType: "Salary Payment",
      otherPartyInfo: "254712345678 - JOHN DOE",
      otherPartyMasked: "2547•••••678 - J. D.",
      linkedTransactionId: null,
      accountNumber: null,
      lineClass: "payout",
      chargeFor: null,
    });
    expect(parsed.lines[2]?.paidInMinor).toBe(10_000_000);
    expect(parsed.lines[5]).toMatchObject({
      details: 'Payment to "ABC, Builders" Ltd',
      withdrawnMinor: 125_050,
    });
  });

  it("reads semicolon and tab separated exports too", () => {
    const rows = [
      "Receipt No.;Completion Time;Paid In;Withdrawn;Details",
      "TKG7AB12CD;2026-11-16 09:15:02;;4000.00;Salary Payment",
    ];
    const semicolon = parseStatementCsv(rows.join("\n"));
    const tab = parseStatementCsv(rows.join("\n").replaceAll(";", "\t"));
    for (const parsed of [semicolon, tab]) {
      expect(parsed.ok && parsed.lines.map((line) => [line.receipt, line.withdrawnMinor])).toEqual([
        ["TKG7AB12CD", 400_000],
      ]);
    }
  });

  it("lists unreadable rows instead of guessing, and keeps the rest", () => {
    const parsed = parseStatementRows([
      ["Receipt No.", "Completion Time", "Paid In", "Withdrawn"],
      ["TKG7AB12CD", "31/11/2026 10:00", "", "100.00"],
      ["TKG7AB12CE", "16/11/2026 10:00", "", "1,00.00"],
      ["TKG7AB12CF", "16/11/2026 10:00", "50.00", "100.00"],
      ["", "16/11/2026 10:00", "", "100.00"],
      ["TKG7AB12CG", "16/11/2026 10:00", "", ""],
      ["TKG7AB12CH", "16/11/2026 10:00", "", "x".repeat(501)],
      ["TKG7AB12CJ", "16/11/2026 10:00 PM", "", "(250.00)"],
      ["Total", "", "", ""],
    ]);
    if (!parsed.ok) throw new Error(parsed.error);
    expect(parsed.issues).toEqual([
      { row: 2, issue: "invalid_time", column: "completionTime" },
      { row: 3, issue: "invalid_amount", column: "withdrawn" },
      { row: 4, issue: "both_amounts", column: null },
      { row: 5, issue: "missing_receipt", column: "receipt" },
      { row: 6, issue: "no_amount", column: null },
      { row: 7, issue: "cell_too_long", column: "withdrawn" },
    ]);
    expect(parsed.lines).toHaveLength(1);
    expect(parsed.lines[0]).toMatchObject({
      receipt: "TKG7AB12CJ",
      completedAt: "2026-11-16T22:00:00+03:00",
      withdrawnMinor: 25_000,
      lineClass: "payout",
    });
  });

  it("refuses files without a statement header or without content", () => {
    expect(parseStatementCsv("")).toEqual({ ok: false, error: "empty" });
    expect(parseStatementCsv("Name,Amount\nJohn,100")).toEqual({ ok: false, error: "no_header" });
    expect(parseStatementRows([["Receipt No.", "Details", "Withdrawn"]])).toEqual({
      ok: false,
      error: "no_header",
    });
  });

  it("parses statement times in the formats exports use (Africa/Nairobi wall clock)", () => {
    expect(parseStatementTime("2026-11-16 14:03:22")).toEqual({
      at: "2026-11-16T14:03:22+03:00",
      date: "2026-11-16",
    });
    expect(parseStatementTime("16/11/2026 2:03 PM")?.at).toBe("2026-11-16T14:03:00+03:00");
    expect(parseStatementTime("16-Nov-2026 00:05:09")?.at).toBe("2026-11-16T00:05:09+03:00");
    expect(parseStatementTime("2026-11-16T14:03:22.000")?.at).toBe("2026-11-16T14:03:22+03:00");
    expect(parseStatementTime(String(excelSerialDate("2026-11-16") + 0.5))).toEqual({
      at: "2026-11-16T12:00:00+03:00",
      date: "2026-11-16",
    });
    expect(parseStatementTime("29/02/2026 10:00")).toBeNull();
    expect(parseStatementTime("16/11/2026 13:00 PM")).toBeNull();
    expect(parseStatementTime("yesterday")).toBeNull();
  });

  it("parses amounts with separators, signs and currency prefixes as absolute minor units", () => {
    expect(parseStatementAmount("1,250.00")).toBe(125_000);
    expect(parseStatementAmount("-1,250")).toBe(125_000);
    expect(parseStatementAmount("(300.5)")).toBe(30_050);
    expect(parseStatementAmount("KES 1 000 000.00")).toBe(100_000_000);
    expect(parseStatementAmount("Ksh.75")).toBe(7_500);
    expect(parseStatementAmount("")).toBeNull();
    expect(parseStatementAmount("12,34")).toBe("invalid");
    expect(parseStatementAmount("1.234")).toBe("invalid");
    expect(parseStatementAmount("1e5")).toBe("invalid");
  });

  it("masks the other party's number and name", () => {
    expect(maskPartyInfo("254712345678 - JOHN KAMAU DOE")).toBe("2547•••••678 - J. K. D.");
    expect(maskPartyInfo("600999 - ABC BUILDERS")).toBe("600999 - A. B.");
  });
});
